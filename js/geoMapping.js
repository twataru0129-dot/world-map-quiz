// data/countries.geojson は Natural Earth (1:50m Admin 0 – Countries) を元に、
// このアプリで使う198の国・地域だけを抽出・簡略化したものです。
//
// 各フィーチャーの properties.code が、countries.js の code / id と対応します。
// ほとんどの国は ISO_A2 の値をそのまま code として使っていますが、
// 元データの ISO_A2 が "-99"（未設定）や特殊な値になっている一部の国・地域だけは
// ISO_A2_EH（拡張版のコード）を採用しています。単純な名前一致ではなく、
// このコード対応を優先して国データと地図データを結び付けています。
//
// 特別な対応が必要だった国・地域:
//   TW（台湾）     … 元データの ISO_A2 が "CN-TW" のため、ISO_A2_EH の "TW" を採用
//   XK（コソボ）   … 元データの ISO_A2 が "-99" のため、ISO_A2_EH の "XK" を採用
//   NO（ノルウェー）… 同上の理由で ISO_A2_EH の "NO" を採用
//   FR（フランス） … 同上の理由で ISO_A2_EH の "FR" を採用
//   PS（パレスチナ）, PR（プエルトリコ）… 元データの ISO_A2 がそのまま一致
//   AU（オーストラリア）… 本土に加えてインド洋の海外領土など計3つのフィーチャーが
//                        同じ code="AU" を持つ。地図描画・タップ判定では
//                        同じ code を持つフィーチャーをすべて「オーストラリア」として扱う。
//
// PDFの2文字コードと地図データ側のコードが一致しない可能性がある、という前提のもと、
// このファイルに変換の根拠を残している。coutries.js 側のコードを変更する場合は、
// data/countries.geojson を作り直す際に使ったスクリプトの対応表も更新すること。
export const GEO_CODE_NOTES = {
  TW: "ISO_A2_EH を採用 (元ISO_A2は CN-TW)",
  XK: "ISO_A2_EH を採用 (元ISO_A2は -99)",
  NO: "ISO_A2_EH を採用 (元ISO_A2は -99)",
  FR: "ISO_A2_EH を採用 (元ISO_A2は -99)",
};
